// Builds figures.js: the constellation figures as seen from Earth, as polylines between the deep sky's stars.
//   git clone --depth 1 https://github.com/astronexus/HYG-Database   (HYG v4.1, CC BY-SA 4.0)
//   git clone --depth 1 https://github.com/ofrohn/d3-celestial       (constellation lines, BSD-3-Clause, Olaf Frohn)
//   node examples/data/build-figures.mjs HYG-Database/hyg/CURRENT/hygdata_v41.csv d3-celestial/data
// Every vertex of d3-celestial's constellations.lines.json (RA / Dec, degrees) is matched to the brightest HYG star within 0.15°;
// that star is the deep sky's own (the nearest 1000 + FAR_STARS, found by position) or, when the deep sky does not have it, it
// goes into FIGURE_STARS (rows like FAR_STARS) so deepsky.js adds it. Out: FIGURE_STARS, and FIGURES as
// [IAU abbreviation, Latin name, English name, [[star name, star name, ...], ...]] (each inner list a polyline).
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { STARS as NEAR } from './stars5000.js';
import { FAR_STARS } from './deepsky-data.js';

const [hygFile, d3Dir] = process.argv.slice(2);
const num = (v) => (v === '' || v == null ? null : Number(v));
const fmt = (v, d = 3) => (v == null || Number.isNaN(v) ? 'null' : String(Math.round(v * 10 ** d) / 10 ** d));
const csv = (line) => line.match(/("([^"]|"")*"|[^,]*)(,|$)/g).map((c) => c.replace(/,$/, '').replace(/^"|"$/g, ''));
const rows = readFileSync(hygFile, 'utf8').trim().split('\n');
const col = Object.fromEntries(csv(rows[0]).map((h, i) => [h, i]));
const label = (r) => r[col.proper] || (r[col.bf] && r[col.bf].trim().replace(/\s+/g, ' ')) || (r[col.hd] && `HD ${r[col.hd]}`) || (r[col.hip] && `HIP ${r[col.hip]}`) || `HYG ${r[col.id]}`;

// the candidates: naked-eye stars with a distance
const hyg = rows
  .slice(1)
  .map(csv)
  .filter((r) => num(r[col.mag]) < 6.8 && num(r[col.dist]) > 0 && num(r[col.dist]) < 1e5 - 1 && r[col.id] !== '0')
  .map((r) => {
    const ra = (num(r[col.ra]) * Math.PI) / 12, dec = (num(r[col.dec]) * Math.PI) / 180;
    return { r, mag: num(r[col.mag]), v: [Math.cos(dec) * Math.cos(ra), Math.cos(dec) * Math.sin(ra), Math.sin(dec)], p: [num(r[col.x]), num(r[col.y]), num(r[col.z])] };
  });

// the deep sky's own stars, by position (parsec)
const scene = [...NEAR.slice(0, 1000), ...FAR_STARS].filter((s) => s[0] !== 'Sol');
const ownName = (p) => scene.find((s) => Math.abs(s[1] - p[0]) < 0.02 && Math.abs(s[2] - p[1]) < 0.02 && Math.abs(s[3] - p[2]) < 0.02)?.[0];

const lines = JSON.parse(readFileSync(join(d3Dir, 'constellations.lines.json'), 'utf8'));
const names = Object.fromEntries(JSON.parse(readFileSync(join(d3Dir, 'constellations.json'), 'utf8')).features.map((f) => [f.id, [f.properties.name, f.properties.en ?? f.properties.name]]));
const COS = Math.cos((0.15 * Math.PI) / 180);
const extra = new Map(); // HYG id -> row
const used = new Map(); // star name -> HYG id (names must stay unique)
let missing = 0;
const starAt = (lon, lat) => {
  const a = (lon * Math.PI) / 180, d = (lat * Math.PI) / 180;
  const v = [Math.cos(d) * Math.cos(a), Math.cos(d) * Math.sin(a), Math.sin(d)];
  let best = null;
  for (const h of hyg) {
    if (h.v[0] * v[0] + h.v[1] * v[1] + h.v[2] * v[2] < COS) continue;
    if (!best || h.mag < best.mag) best = h;
  }
  if (!best) return (missing++, null);
  let name = ownName(best.p);
  if (!name) {
    name = label(best.r);
    extra.set(best.r[col.id], best.r);
  }
  const id = best.r[col.id];
  if (used.has(name) && used.get(name) !== id) throw new Error(`two stars called ${name}`);
  used.set(name, id);
  return name;
};
const figures = lines.features.map((f) => {
  const polys = [];
  for (const line of f.geometry.coordinates) {
    let cur = [];
    for (const [lon, lat] of line) {
      const s = starAt(lon, lat);
      if (s && cur.at(-1) !== s) cur.push(s);
      else if (!s) (cur.length > 1 && polys.push(cur), (cur = []));
    }
    if (cur.length > 1) polys.push(cur);
  }
  // Serpens is two figures with one id: the head (west of Ophiuchus, RA ~15.5h) and the tail (RA ~18h)
  if (f.id === 'Ser') {
    const lons = f.geometry.coordinates.flat().map(([lon]) => (lon < 0 ? lon + 360 : lon));
    const caput = lons.reduce((a, b) => a + b, 0) / lons.length < 255;
    return [f.id, caput ? 'Serpens Caput' : 'Serpens Cauda', caput ? 'Serpent\'s Head' : 'Serpent\'s Tail', polys];
  }
  return [f.id, ...(names[f.id] ?? [f.id, f.id]), polys];
});
const starLine = (r) => `  [${JSON.stringify(label(r))},${fmt(num(r[col.x]))},${fmt(num(r[col.y]))},${fmt(num(r[col.z]))},${fmt(num(r[col.absmag]), 2)},${JSON.stringify(r[col.spect] ?? '')},${fmt(num(r[col.ci]))},${fmt(num(r[col.lum]))}],`;
writeFileSync(
  new URL('./figures.js', import.meta.url),
  [
    '// Generated by build-figures.mjs from HYG v4.1 (astronexus, CC BY-SA 4.0) and d3-celestial constellation lines (Olaf Frohn, BSD-3-Clause). Do not edit.',
    '// FIGURE_STARS: the figure stars the deep sky did not have, as FAR_STARS rows: [name, x, y, z (equatorial, parsec), absMag, spect, B-V, luminosity]',
    'export const FIGURE_STARS = [',
    ...[...extra.values()].map(starLine),
    '];',
    '// FIGURES: [IAU abbreviation, Latin name, English name, polylines of star names]',
    'export const FIGURES = [',
    ...figures.map((f) => `  ${JSON.stringify(f)},`),
    '];',
    '',
  ].join('\n'),
);
const segs = figures.reduce((s, f) => s + f[3].reduce((t, p) => t + p.length - 1, 0), 0);
console.log(figures.length, 'figures,', segs, 'segments,', extra.size, 'stars added,', missing, 'vertices without a star');
