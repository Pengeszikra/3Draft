// Builds examples/data/deepsky-data.js for the deep-sky stress test from two open catalogues:
//   git clone --depth 1 https://github.com/astronexus/HYG-Database   (HYG v4.1, CC BY-SA 4.0)
//   git clone --depth 1 https://github.com/mattiaverga/OpenNGC        (OpenNGC, CC BY-SA 4.0)
//   node examples/data/build-deepsky.mjs HYG-Database/hyg/CURRENT/hygdata_v41.csv OpenNGC/database_files/NGC.csv
// Out: FAR_STARS, the 2000 most notable stars beyond the nearest 1000 (named ones first, then Bayer / Flamsteed ones, each by
// apparent brightness), as [name, x, y, z (pc), absMag, spect, ci, lum]; NGC, the brightest galaxies with a usable recession
// velocity, as [name, RA h, Dec deg, distance Mly (v / H0), diameter kly, Hubble type, axis ratio, position angle deg].
import { readFileSync, writeFileSync } from 'node:fs';
import { gunzipSync } from 'node:zlib';
import { STARS as NEAR } from './stars5000.js';

const [hygFile, ngcFile] = process.argv.slice(2);
const text = (f) => (f.endsWith('.gz') ? gunzipSync(readFileSync(f)) : readFileSync(f)).toString('utf8');
const num = (v) => (v === '' || v == null ? null : Number(v));
const fmt = (v, d = 6) => (v == null || Number.isNaN(v) ? 'null' : String(Math.round(v * 10 ** d) / 10 ** d));

// ---- stars
const csv = (line) => line.match(/("([^"]|"")*"|[^,]*)(,|$)/g).map((c) => c.replace(/,$/, '').replace(/^"|"$/g, ''));
const rows = text(hygFile).trim().split('\n');
const head = csv(rows[0]);
const col = Object.fromEntries(head.map((h, i) => [h, i]));
const PC = 3.26156;
// the nearest 1000 (the near list) end here; everything farther is a candidate
const nearDist = (r) => Math.hypot(r[1], r[2], r[3]);
const cutoff = nearDist(NEAR[999]);
const label = (r) => r[col.proper] || (r[col.bf] && r[col.bf].trim().replace(/\s+/g, ' ')) || (r[col.hd] && `HD ${r[col.hd]}`) || (r[col.hip] && `HIP ${r[col.hip]}`) || `HYG ${r[col.id]}`;
const far = rows
  .slice(1)
  .map(csv)
  .filter((r) => {
    const d = num(r[col.dist]);
    return d > cutoff && d < 1e5 - 1;
  })
  .map((r) => ({ r, rank: r[col.proper] ? 0 : r[col.bf]?.trim() ? 1 : 2, mag: num(r[col.mag]) ?? 99 }))
  .sort((a, b) => a.rank - b.rank || a.mag - b.mag)
  .slice(0, 2000)
  .map(({ r }) => r);
const starLine = (r) => `  [${JSON.stringify(label(r))},${fmt(num(r[col.x]), 3)},${fmt(num(r[col.y]), 3)},${fmt(num(r[col.z]), 3)},${fmt(num(r[col.absmag]), 2)},${JSON.stringify(r[col.spect] ?? '')},${fmt(num(r[col.ci]), 3)},${fmt(num(r[col.lum]), 3)}],`;

// ---- galaxies
const ngcRows = text(ngcFile).trim().split('\n').map((l) => l.split(';'));
const nh = Object.fromEntries(ngcRows[0].map((h, i) => [h, i]));
const hms = (s) => { const [h, m, x] = s.split(':').map(Number); return h + m / 60 + x / 3600; };
const dms = (s) => { const sg = s.startsWith('-') ? -1 : 1; const [d, m, x] = s.replace(/^[+-]/, '').split(':').map(Number); return sg * (d + m / 60 + x / 3600); };
const H0 = 70; // km/s/Mpc
const pretty = (id) => id.replace(/^(NGC|IC)0*(\d+)/, '$1 $2');
const gal = ngcRows
  .slice(1)
  .filter((r) => r[nh.Type] === 'G' && num(r[nh.RadVel]) > 1000 && num(r[nh.MajAx]) > 0 && r[nh.RA] && r[nh.Dec])
  .map((r) => {
    const v = num(r[nh.RadVel]);
    const mly = ((v / H0) * PC);
    const maj = num(r[nh.MajAx]);
    const kly = (mly * 1e3 * maj * Math.PI) / (180 * 60);
    const min = num(r[nh.MinAx]);
    const mag = num(r[nh['V-Mag']]) ?? (num(r[nh['B-Mag']]) != null ? num(r[nh['B-Mag']]) - 0.8 : 99);
    const common = r[nh['Common names']]?.split(',')[0]?.trim();
    const m = r[nh.M] ? `M${Number(r[nh.M])}` : '';
    const id = pretty(r[nh.Name]);
    const name = [common, m, id].filter(Boolean).filter((x, i, a) => a.indexOf(x) === i).join(' · ');
    return { name, id, m, ra: hms(r[nh.RA]), dec: dms(r[nh.Dec]), mly, kly, type: r[nh.Hubble] || '', q: min && maj ? min / maj : null, pa: num(r[nh.PosAng]), mag };
  })
  .sort((a, b) => a.mag - b.mag)
  .slice(0, 1000);
// the curated nearby list (with real distances) needs the axes and position angles too: every NGC/IC/M row by its id
const axes = {};
for (const r of ngcRows.slice(1)) {
  if (r[nh.Type] !== 'G') continue;
  const maj = num(r[nh.MajAx]), min = num(r[nh.MinAx]);
  const rec = [maj && min ? Math.round((min / maj) * 1000) / 1000 : null, num(r[nh.PosAng]), r[nh.Hubble] || ''];
  axes[pretty(r[nh.Name])] = rec;
  if (r[nh.M]) axes[`M${Number(r[nh.M])}`] = rec;
}
const galLine = (g) => `  [${JSON.stringify(g.name)},${fmt(g.ra, 5)},${fmt(g.dec, 4)},${fmt(g.mly, 2)},${fmt(g.kly, 1)},${JSON.stringify(g.type)},${fmt(g.q, 3)},${fmt(g.pa, 0)}],`;

const out = [
  '// Generated by build-deepsky.mjs from HYG v4.1 (astronexus) and OpenNGC (Mattia Verga), both CC BY-SA 4.0. Do not edit.',
  '// FAR_STARS: [name, x, y, z (equatorial, parsec), absMag, spect, B-V, luminosity (Lsun)]',
  'export const FAR_STARS = [',
  ...far.map(starLine),
  '];',
  '// NGC: [name, RA hours, Dec degrees, distance Mly (recession velocity / 70 km/s/Mpc), diameter kly, Hubble type, minor/major axis, position angle]',
  'export const NGC = [',
  ...gal.map(galLine),
  '];',
  '// AXES: id -> [minor/major axis, position angle, Hubble type], for galaxies known from other lists',
  `export const AXES = ${JSON.stringify(axes)};`,
  '',
].join('\n');
writeFileSync(new URL('./deepsky-data.js', import.meta.url), out);
const fd = far.map((r) => num(r[col.dist]) * PC);
console.log(far.length, 'far stars', Math.round(Math.min(...fd)), '-', Math.round(Math.max(...fd)), 'ly;', gal.length, 'galaxies', Math.round(Math.min(...gal.map((g) => g.mly))), '-', Math.round(Math.max(...gal.map((g) => g.mly))), 'Mly;', (out.length / 1e3).toFixed(0), 'KB');
